export const DICTIONARIES: Record<Language, Dictionary> = { en, ru, kk };

/**
 * Looks a message up and fills in its `{placeholders}`.
 *
 * A key with no translation falls back to English rather than showing the key
 * itself: a visitor should never be shown `orders.repeatTitle`.
 */
export function translate(language: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = DICTIONARIES[language]?.[key] ?? DICTIONARIES.en[key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}
